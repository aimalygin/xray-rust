fn network(name: &str) -> Network {
    match name {
        "tcp" => Network::Tcp,
        "udp" => Network::Udp,
        other => panic!("unknown network {other}"),
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

#[test]
fn headers_match_go_proxyproto() {
    for &(version, source_network, source, connection_network, destination, expected) in ORACLE {
        let version = match version {
            1 => ProxyProtocolVersion::V1,
            2 => ProxyProtocolVersion::V2,
            other => panic!("unknown version {other}"),
        };
        let source = (!source_network.is_empty()).then(|| InboundSource {
            addr: source.parse().unwrap(),
            network: network(source_network),
        });
        let header = header(
            version,
            source,
            network(connection_network),
            destination.parse().unwrap(),
        );
        assert_eq!(
            hex(&header),
            expected,
            "{version:?} {source:?} -> {connection_network} {destination}"
        );
    }
}
